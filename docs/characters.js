function characterIntro(chapter,id){
  const profile=CHARACTER_PROFILES[id];
  const cast=ANIME_ARCS[chapter.id]?.cast.find(([castId])=>String(castId)===id);
  const names=[...CHARACTER_NAMES].filter(([,profileId])=>profileId===id).map(([name])=>name);
  const people=chapter.people.find(([label])=>names.some(name=>label.includes(name)));
  return CHAPTER_CHARACTER_INTROS[chapter.id]?.[id] || profile.chapters?.[chapter.id] || cast?.[1] || people?.[1];
}
